    case when flights_text ~ '^[0-9]+([.]0+)?$' then flights_text::numeric::smallint end as flight_count,
    case when distance_text ~ '^[0-9]+([.][0-9]+)?$' then distance_text::numeric(10, 2) end as distance_miles,
    case when distance_group_text ~ '^[0-9]+([.]0+)?$' then distance_group_text::numeric::smallint end as distance_group,

    case when carrier_delay_text ~ '^[0-9]+([.]0+)?$' then carrier_delay_text::numeric::integer end as carrier_delay_minutes,
    case when weather_delay_text ~ '^[0-9]+([.]0+)?$' then weather_delay_text::numeric::integer end as weather_delay_minutes,
    case when nas_delay_text ~ '^[0-9]+([.]0+)?$' then nas_delay_text::numeric::integer end as nas_delay_minutes,
    case when security_delay_text ~ '^[0-9]+([.]0+)?$' then security_delay_text::numeric::integer end as security_delay_minutes,
    case when late_aircraft_delay_text ~ '^[0-9]+([.]0+)?$' then late_aircraft_delay_text::numeric::integer end as late_aircraft_delay_minutes,

    {{ bts_hhmm_to_time('first_dep_time') }} as first_departure_time,
    {{ bts_hhmm_to_time('first_dep_time', part='day_offset') }} as first_departure_day_offset,
