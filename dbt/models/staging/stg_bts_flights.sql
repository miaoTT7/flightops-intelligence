    case when destination_airport_id_text ~ '^[0-9]+$' then destination_airport_id_text::integer end as destination_airport_id,
    case when destination_airport_sequence_id_text ~ '^[0-9]+$' then destination_airport_sequence_id_text::integer end as destination_airport_sequence_id,
    case when destination_city_market_id_text ~ '^[0-9]+$' then destination_city_market_id_text::integer end as destination_city_market_id,
    destination_airport_code,
    destination_city_name,
    destination_state_code,
    destination_state_fips_text as destination_state_fips,
    destination_state_name,
    case when destination_world_area_code_text ~ '^[0-9]+$' then destination_world_area_code_text::smallint end as destination_world_area_code,

    {{ bts_hhmm_to_time('crs_dep_time') }} as scheduled_departure_time,
    {{ bts_hhmm_to_time('crs_dep_time', part='day_offset') }} as scheduled_departure_day_offset,
