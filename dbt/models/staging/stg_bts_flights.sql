    case when departure_delay_minutes_text ~ '^[0-9]+([.]0+)?$' then departure_delay_minutes_text::numeric::integer end as departure_delay_minutes,
    case when departure_delayed_15_text ~ '^1([.]0+)?$' then true when departure_delayed_15_text ~ '^0([.]0+)?$' then false end as is_departure_delayed_15_minutes,
    case when departure_delay_group_text ~ '^[+-]?[0-9]+([.]0+)?$' then departure_delay_group_text::numeric::smallint end as departure_delay_group,
    departure_time_block,
    case when taxi_out_text ~ '^[0-9]+([.]0+)?$' then taxi_out_text::numeric::integer end as taxi_out_minutes,
    {{ bts_hhmm_to_time('wheels_off') }} as wheels_off_time,
    {{ bts_hhmm_to_time('wheels_off', part='day_offset') }} as wheels_off_day_offset,
    {{ bts_hhmm_to_time('wheels_on') }} as wheels_on_time,
