    {{ generate_key(['source_file_id', 'source_row_number']) }} as flight_record_key,
    source_file_id,
    batch_id,
    source_row_number,
    ingested_at,

    case when year_text ~ '^[0-9]{4}$' then year_text::smallint end as flight_year,
    case when quarter_text ~ '^[1-4]$' then quarter_text::smallint end as flight_quarter,
    case when month_text ~ '^(0?[1-9]|1[0-2])$' then month_text::smallint end as flight_month,
    case when day_of_month_text ~ '^([1-9]|[12][0-9]|3[01])$' then day_of_month_text::smallint end as day_of_month,
    case when day_of_week_text ~ '^[1-7]$' then day_of_week_text::smallint end as day_of_week,
    case when flight_date_text ~ '^[0-9]{4}-[0-9]{2}-[0-9]{2}$' then flight_date_text::date end as flight_date,

    reporting_airline as reporting_airline_code,
    case when dot_airline_id_text ~ '^[0-9]+$' then dot_airline_id_text::integer end as dot_airline_id,
    iata_airline_code,
    tail_number,
    flight_number,

    case when origin_airport_id_text ~ '^[0-9]+$' then origin_airport_id_text::integer end as origin_airport_id,
    case when origin_airport_sequence_id_text ~ '^[0-9]+$' then origin_airport_sequence_id_text::integer end as origin_airport_sequence_id,
