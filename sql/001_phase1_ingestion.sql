-- Phase 1.2: source lineage, ingestion attempts, and untouched BTS values.
CREATE SCHEMA IF NOT EXISTS ingestion;
CREATE SCHEMA IF NOT EXISTS raw;

CREATE TABLE IF NOT EXISTS ingestion.source_file (
    source_file_id bigint GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
    dataset_name text NOT NULL,
    source_year smallint NOT NULL,
    source_month smallint NOT NULL CHECK (source_month BETWEEN 1 AND 12),
    original_filename text NOT NULL,
    first_seen_relative_path text NOT NULL,
    csv_member_name text,
    csv_sha256 char(64) NOT NULL,
    csv_size_bytes bigint NOT NULL CHECK (csv_size_bytes >= 0),
    schema_fingerprint char(64) NOT NULL,
    expected_row_count bigint NOT NULL CHECK (expected_row_count >= 0),
    has_empty_trailing_column boolean NOT NULL,
    discovered_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    CONSTRAINT uq_source_file_content UNIQUE (dataset_name, csv_sha256),
    CONSTRAINT uq_source_file_period UNIQUE (dataset_name, source_year, source_month)
);

CREATE TABLE IF NOT EXISTS ingestion.ingestion_batch (
    batch_id uuid PRIMARY KEY,
    source_file_id bigint NOT NULL REFERENCES ingestion.source_file(source_file_id),
    attempt_number integer NOT NULL CHECK (attempt_number > 0),
    status text NOT NULL CHECK (status IN ('running', 'succeeded', 'failed', 'skipped')),
    input_filename text NOT NULL,
    input_relative_path text NOT NULL,
    container_type text NOT NULL CHECK (container_type IN ('csv', 'zip')),
    archive_sha256 char(64),
    archive_size_bytes bigint NOT NULL CHECK (archive_size_bytes >= 0),
    started_at timestamptz NOT NULL DEFAULT clock_timestamp(),
    completed_at timestamptz,
    rows_read bigint NOT NULL DEFAULT 0 CHECK (rows_read >= 0),
    rows_loaded bigint NOT NULL DEFAULT 0 CHECK (rows_loaded >= 0),
    rows_rejected bigint NOT NULL DEFAULT 0 CHECK (rows_rejected >= 0),
    error_stage text,
    error_type text,
    error_message text,
    CONSTRAINT uq_batch_attempt UNIQUE (source_file_id, attempt_number)
);

CREATE UNIQUE INDEX IF NOT EXISTS uq_one_successful_batch_per_source
    ON ingestion.ingestion_batch(source_file_id)
    WHERE status = 'succeeded';

